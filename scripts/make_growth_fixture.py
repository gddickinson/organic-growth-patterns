"""Write tests/fixtures/growth_fixture.json: runs of the repo's real generators that the JS engine must reproduce.

Each case is replayed by web/simulate.py (np.random.seed + OrganicPatternGenerator / OrganicPattern3D) and stores the
active-cell count after every growth step plus the final grid. web/static/growth_engine.test.mjs replays the same
actions in JavaScript; tests/test_web.py checks this file is still what the Python code produces.

Run: python scripts/make_growth_fixture.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from web.simulate import (grid_2d_payload, grid_3d_payload, patterns_payload, replay_2d,  # noqa: E402
                          replay_3d)

OUT = ROOT / "tests" / "fixtures" / "growth_fixture.json"
SEEDS_2D = [["seed_random", 0.3], ["seed_center", 6], ["seed_line"]]
SEEDS_3D = [["seed_random", 0.1], ["seed_center", 3]]


def cases_2d():
    cases, rng_seed = [], 1
    for pattern in ("coral", "lichen", "mycelium"):
        for seed in SEEDS_2D:
            actions = [seed, ["grow", pattern, 6], ["env", "light"], ["grow", pattern, 2],
                       ["env", "moisture"], ["grow", pattern, 2]]
            cases.append({"width": 23, "height": 17, "rng_seed": rng_seed, "actions": actions})
            rng_seed += 1
    cases.append({"width": 31, "height": 29, "rng_seed": 4242,   # switching rules mid-run, density edge cases
                  "actions": [["seed_random", 0.55], ["grow", "lichen", 3], ["grow", "mycelium", 2],
                              ["grow", "coral", 3], ["seed_random", 1.0], ["grow", "coral", 1],
                              ["seed_random", 0.0], ["grow", "lichen", 1]]})
    cases.append({"width": 100, "height": 100, "rng_seed": 7,     # the desktop demo: 100x100, density 0.3, 30 gens
                  "actions": [["seed_random", 0.3], ["grow", "coral", 30], ["env", "light"]]})
    return cases


def cases_3d():
    cases, rng_seed = [], 100
    for pattern in ("coral", "mycelium", "crystal"):
        for seed in SEEDS_3D:
            cases.append({"width": 13, "height": 11, "depth": 9, "rng_seed": rng_seed,
                          "actions": [seed, ["grow", pattern, 5]]})
            rng_seed += 1
    cases.append({"width": 30, "height": 30, "depth": 30, "rng_seed": 0,   # the 3D desktop demo
                  "actions": [["seed_center", 3], ["grow", "crystal", 10]]})
    return cases


def build():
    two = []
    for c in cases_2d():
        gen, counts = replay_2d(c["width"], c["height"], c["rng_seed"], c["actions"])
        two.append({**c, "expect": grid_2d_payload(gen, counts)})
    three = []
    for c in cases_3d():
        gen, counts = replay_3d(c["width"], c["height"], c["depth"], c["rng_seed"], c["actions"])
        three.append({**c, "expect": grid_3d_payload(gen, counts)})
    mt = []
    for s in (0, 1, 12345, 2 ** 32 - 1):
        np.random.seed(s)
        mt.append({"seed": s, "random": [float(v) for v in np.random.random_sample(5)]})
    return {"note": "generated by scripts/make_growth_fixture.py from the repo's Python generators",
            "numpy": np.__version__, "patterns": patterns_payload(), "mt19937": mt, "cases_2d": two, "cases_3d": three}


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    data = build()
    OUT.write_text(json.dumps(data, separators=(",", ":")))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['cases_2d'])} 2D + {len(data['cases_3d'])} 3D cases, "
          f"{OUT.stat().st_size / 1e3:.0f} kB")
